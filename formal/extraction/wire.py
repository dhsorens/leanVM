"""Wire the Lean packages hax scaffolds beside the crates into the extraction workspace.

Run by `hax.sh extract` after every extraction, so that a crate takes part by declaring a scenario
in its hax.toml and nothing else. For each package crates/<crate>/proofs/<scenario>/lean:

- Assumptions/*External.lean is kept in step with the templates hax regenerates: each declaration
  is the template's, in its order, so a signature follows the Rust, except one fixed by hand,
  which carries a `-- hand-maintained: <why>` line and is kept as it is while the template still
  declares it. Every `fmt` loses the `Formatter`
  write-back Aeneas gives it, which the hax Lean library's `Debug` and `Display` do not have
  (hax seeds a new package's Assumptions/ from the raw template, so the seeded ones need it too).
  Both import CoreModelsExt, the standard-library models every extraction shares.
- Its lakefile requires CoreModelsExt and resolves its dependencies into the workspace's
  `.lake/packages`, and its manifest is the workspace's, so the package builds the same alone.

The workspace (this directory) requires every package by path, and its library `Extraction` has
one root per package, `Extraction.<Package>`, so building it builds each extraction on its own:
two extractions are never imported together, since a crate's extraction declares the items it
uses from another crate as its own opaque ones.
"""

import json
import os
import pathlib
import re
import subprocess

ROOT = pathlib.Path(subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip())
WORKSPACE = ROOT / "formal" / "extraction"
EXT = WORKSPACE / "CoreModelsExt"
STEMS = ("TypesExternal", "FunsExternal")
DECLARATION = re.compile(r"\n(?:axiom|opaque|def|structure|inductive|abbrev)\s+(\S+)")
FORMATTER_WRITE_BACK = re.compile(r"\s*×\s*\(core\.fmt\.Formatter\s*→\s*core\.fmt\.Formatter\)\)")
HAND_MAINTAINED = "\n-- hand-maintained:"
GENERATED = "# Generated by formal/extraction/wire.py from the packages beside the crates; do not edit.\n"


def relative(path, start):
    return os.path.relpath(path, start)


def write(path, text):
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def split(text):
    """The header, then each declaration's block (its doc comment and body) by name."""
    start = text.find("\n/-- ")
    if start < 0:
        return text, {}
    blocks = {}
    for block in re.split(r"(?=\n/-- )", text[start:]):
        match = DECLARATION.search(block)
        if match:
            blocks[match.group(1)] = block
    return text[:start], blocks


def drop_formatter_write_back(block):
    if ".Insts.CoreFmtDebug.fmt" in block or ".Insts.CoreFmtDisplay.fmt" in block:
        return FORMATTER_WRITE_BACK.sub(")", block)
    return block


def sync_assumptions(package, name):
    for stem in STEMS:
        template = package / name / "Extraction" / f"{stem}_Template.lean"
        assumption = package / name / "Assumptions" / f"{stem}.lean"
        if not template.exists() or not assumption.exists():
            continue
        _, wanted = split(template.read_text())
        header, present = split(assumption.read_text())
        if "public import CoreModelsExt\n" not in header:
            header = header.replace("public import CoreModels\n", "public import CoreModels\npublic import CoreModelsExt\n", 1)
        kept = {key: block for key, block in present.items() if HAND_MAINTAINED in block}
        text = header + "".join(drop_formatter_write_back(kept.get(key) or block) for key, block in wanted.items())
        write(assumption, text if text.endswith("\n") else text + "\n")
        for key in wanted.keys() - present.keys():
            print(f"{assumption.relative_to(ROOT)}: added {key}")
        for key in present.keys() - wanted.keys():
            print(f"{assumption.relative_to(ROOT)}: dropped {key}")


def wire_lakefile(package):
    lakefile = package / "lakefile.toml"
    text = lakefile.read_text()
    packages_dir = relative(WORKSPACE / ".lake" / "packages", package)
    if "\npackagesDir = " not in text:
        text = re.sub(
            r"(\ndefaultTargets = .*\n)",
            r"\1# Shared with every extraction: the workspace in formal/extraction resolves the dependencies once.\n"
            + f'packagesDir = "{packages_dir}"\n',
            text,
            count=1,
        )
    if '\nname = "CoreModelsExt"\n' not in text:
        text += f'\n[[require]]\nname = "CoreModelsExt"\npath = "{relative(EXT, package)}"\n'
    write(lakefile, text)


def package_manifest(package, name, workspace_manifest):
    """The workspace's manifest, seen from the package: its git dependencies, and CoreModelsExt."""
    entries = []
    for entry in workspace_manifest["packages"]:
        if entry["type"] == "git":
            entries.append(entry)
        elif entry["name"] == "CoreModelsExt":
            entries.append(dict(entry, dir=relative(EXT, package)))
    manifest = dict(workspace_manifest, name=name, packagesDir=relative(WORKSPACE / ".lake" / "packages", package), packages=entries)
    write(package / "lake-manifest.json", json.dumps(manifest, indent=1, ensure_ascii=False) + "\n")


def lean_name(package):
    return re.search(r'^name = "([^"]+)"', (package / "lakefile.toml").read_text(), re.M).group(1)


def main():
    packages = sorted(path for path in ROOT.glob("crates/*/proofs/*/lean") if (path / "lakefile.toml").exists())
    names = {package: lean_name(package) for package in packages}

    lakefile = [
        GENERATED,
        "# The workspace of every hax extraction (formal/extraction/README.md): each package beside its\n",
        "# crate is required by path, so their shared dependencies resolve once, in this directory.\n",
        'name = "extraction"\ndefaultTargets = ["Extraction"]\n\n[[lean_lib]]\nname = "Extraction"\n',
        "roots = [" + ", ".join(f'"Extraction.{names[p]}"' for p in packages) + "]\n",
        f'\n[[require]]\nname = "CoreModelsExt"\npath = "{relative(EXT, WORKSPACE)}"\n',
    ]
    lakefile += [f'\n[[require]]\nname = "{names[p]}"\npath = "{relative(p, WORKSPACE)}"\n' for p in packages]
    write(WORKSPACE / "lakefile.toml", "".join(lakefile))

    roots = WORKSPACE / "Extraction"
    roots.mkdir(exist_ok=True)
    for stale in roots.glob("*.lean"):
        if stale.stem not in names.values():
            stale.unlink()
    for package in packages:
        write(roots / f"{names[package]}.lean", f"-- Generated by formal/extraction/wire.py.\nimport {names[package]}\n")

    manifest_path = WORKSPACE / "lake-manifest.json"
    manifest = json.loads(manifest_path.read_text())
    git = [entry for entry in manifest["packages"] if entry["type"] == "git"]
    path = [
        {
            "type": "path",
            "scope": "",
            "name": name,
            "manifestFile": "lake-manifest.json",
            "inherited": False,
            "dir": dir,
            "copy": False,
            "configFile": "lakefile.toml",
        }
        for name, dir in [("CoreModelsExt", relative(EXT, WORKSPACE))] + [(names[p], relative(p, WORKSPACE)) for p in packages]
    ]
    manifest["packages"] = path + git
    write(manifest_path, json.dumps(manifest, indent=1, ensure_ascii=False) + "\n")

    package_manifest(EXT, "CoreModelsExt", dict(manifest, packages=git))
    for package in packages:
        sync_assumptions(package, names[package])
        wire_lakefile(package)
        package_manifest(package, names[package], manifest)


if __name__ == "__main__":
    main()
